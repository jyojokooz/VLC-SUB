function descriptor()
    return {
        title = "Universal Subtitles AI",
        version = "4.0.3.0",
        author = "Joel S Raphael",
        url = "http://universalsubtitles.ai",
        shortdesc = "Launch Universal Subtitles AI",
        description = "Seamlessly generate and apply subtitles without interrupting playback.",
        capabilities = {"playing-listener"}
    }
end

local dlg = nil
local timer = nil

function activate()
    create_dialog()
    
    -- Start an automatic background timer (checks for the Python signal file every 1 second)
    -- This allows the subtitle to apply magically like VLsub!
    pcall(function()
        if vlc.timer and vlc.timer.ex then
            timer = vlc.timer.ex(check_signal_file)
            timer:start(1)
        end
    end)
end

function deactivate()
    -- Stop the timer when the window is closed
    if timer then
        pcall(function() timer:stop() end)
    end
end

function close()
    vlc.deactivate()
end

function create_dialog()
    dlg = vlc.dialog("Universal Subtitles AI")
    dlg:add_label("<b>1. Start the Toolkit</b>", 1, 1, 3, 1)
    dlg:add_button("Launch Toolkit", click_open_app, 1, 2, 3, 1)
    
    dlg:add_label("<b>2. Apply Subtitles (Smoothly)</b>", 1, 3, 3, 1)
    dlg:add_label("Subtitles will be applied instantly without restarting your video.", 1, 4, 3, 1)
    dlg:add_button("Apply Latest Subtitle", click_apply_sub, 1, 5, 3, 1)
end

-- This function reads the path generated by Python and injects it instantly
function check_signal_file()
    local roaming_appdata = os.getenv("APPDATA")
    if not roaming_appdata then return end
    
    local signal_file = roaming_appdata .. "\\UniversalSubtitles\\apply_sub.txt"
    local f = io.open(signal_file, "r")
    
    if f then
        local sub_path = f:read("*all")
        f:close()
        os.remove(signal_file) -- clean up the trigger file
        
        if sub_path and sub_path ~= "" then
            -- Inject the subtitle into the CURRENT running video without restarting!
            vlc.input.add_subtitle(sub_path, true)
        end
    end
end

function click_apply_sub()
    -- If the automatic timer is unsupported on their VLC, they can just click the button
    check_signal_file()
end

function urlencode(str)
    if str then
        str = string.gsub(str, "([^%w %-%_%.%~])", function(c)
            return string.format("%%%02X", string.byte(c))
        end)
        str = string.gsub(str, " ", "%%20")
    end
    return str
end

function click_open_app()
    local item = vlc.input.item()
    local video_path = ""
    
    if item then
        local uri = item:uri()
        if string.sub(uri, 1, 8) == "file:///" then
            video_path = vlc.strings.decode_uri(string.sub(uri, 9))
            video_path = string.gsub(video_path, "/", "\\") 
        end
    end

    local local_appdata = os.getenv("LOCALAPPDATA")
    local roaming_appdata = os.getenv("APPDATA")
    local program_files = os.getenv("PROGRAMFILES")
    local program_files_x86 = os.getenv("PROGRAMFILES(X86)")
    local exe_path = ""

    -- UPDATED: Added the Microsoft Store WindowsApps path!
    local normal_paths = {
        local_appdata .. "\\Microsoft\\WindowsApps\\UniversalSubtitles.exe",
        local_appdata .. "\\Programs\\UniversalSubtitleToolkit\\UniversalSubtitles.exe",
        roaming_appdata .. "\\Programs\\UniversalSubtitleToolkit\\UniversalSubtitles.exe",
        program_files .. "\\UniversalSubtitleToolkit\\UniversalSubtitles.exe",
        program_files_x86 .. "\\UniversalSubtitleToolkit\\UniversalSubtitles.exe"
    }

    for _, path in ipairs(normal_paths) do
        local f = io.open(path, "r")
        if f then
            f:close()
            exe_path = path
            break
        end
    end

    if exe_path ~= "" then
        local cmd = ""
        if video_path ~= "" then
            cmd = 'start "" "' .. exe_path .. '" "' .. video_path .. '"'
        else
            cmd = 'start "" "' .. exe_path .. '"'
        end
        os.execute(cmd)
    else
        local launch_uri = "universalsubtitles://"
        if video_path ~= "" then
            launch_uri = launch_uri .. "?video=" .. urlencode(video_path)
        end
        local cmd = 'start "" "' .. launch_uri .. '"'
        os.execute(cmd)
    end
    
    -- IMPORTANT FIX: 
    -- We removed `vlc.deactivate()` here so the VLC window stays open in the background!
    -- This keeps our timer alive to automatically apply the subtitles when Python finishes.
end